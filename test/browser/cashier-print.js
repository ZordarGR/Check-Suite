/* The shipped cashier summary, its shared print routing and real Chromium PDF. */
require('./fresh.js')();
const {chromium}=require('playwright-core'),assert=require('assert/strict'),fs=require('fs'),path=require('path'),os=require('os'),http=require('http'),cp=require('child_process');
(async()=>{
 const html=fs.readFileSync(path.join(__dirname,'h-sweep.html'));
 const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(html)});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'cashier-print-'));let browser;
 try{
  browser=await chromium.launch({executablePath:process.env.PW_BROWSER||'/usr/bin/chromium',args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1180,height:860}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{window.__prints=0;window.print=()=>{window.dispatchEvent(new Event('beforeprint'));window.__prints++;};});
  await page.goto('http://127.0.0.1:'+server.address().port);await page.locator('#cashierBtn').click();
  assert(await page.locator('#cashierPrint').isDisabled(),'incomplete count cannot print a valid summary');
  const count=i=>page.locator('#cashierCounts input').nth(i);
  const amount=(i,v)=>page.locator('#cashierAmount'+i).fill(v);
  await count(9).fill('50');await count(12).fill('2');await amount(1,'125.25');await amount(2,'74.75');
  assert.equal(await page.locator('#cashierResult').getAttribute('data-verdict'),'ok');
  await page.evaluate(()=>{
   window.__t.setModel({reportDate:'SYNTHETIC AUDIT DATE',receipts:[],depts:{},validation:[]});
   window.__t.setState({date:'19/10/2026',receipts:{},extras:[]});
  });
  const storage=await page.evaluate(()=>JSON.stringify(Object.fromEntries(Object.entries(localStorage))));
  await page.locator('#cashierPrint').click();
  assert.equal(await page.locator('#pvPaper tbody').first().locator('tr').count(),2,'only non-zero denominations');
  const preview=await page.locator('#pvPaper').textContent();
  for(const text of ['Income summary','125.25 €','74.75 €','200.00 €','500.00 €','700.00 €','OK'])assert(preview.includes(text),text);
  assert(!preview.includes('SYNTHETIC AUDIT DATE'));
  await page.screenshot({path:path.join(__dirname,'cashier-print.png'),fullPage:true});
  await page.locator('#pvGo').click();await page.waitForFunction(()=>window.__prints===1);
  const sheet=await page.locator('#printSheet').innerHTML();
  await page.evaluate(()=>{window.dispatchEvent(new Event('afterprint'));window.dispatchEvent(new Event('beforeprint'));});
  assert.equal(await page.locator('#printSheet').innerHTML(),sheet,'preview rerenders retain the same snapshot');
  assert.equal(await page.locator('#dlOrient').textContent(),'','portrait with ordinary margins');
  const pdf=path.join(tmp,'summary.pdf');await page.pdf({path:pdf,format:'A4',preferCSSPageSize:true,printBackground:true});
  const pdfText=cp.execFileSync('pdftotext',[pdf,'-'],{encoding:'utf8'}),info=cp.execFileSync('pdfinfo',[pdf],{encoding:'utf8'});
  assert(/Pages:\s+1\b/.test(info),'one PDF page');const size=info.match(/Page size:\s+([\d.]+) x ([\d.]+) pts/);assert(size&&Math.abs(+size[1]-595.28)<2&&Math.abs(+size[2]-841.89)<2,'A4 portrait: '+info);
  assert(pdfText.includes('Income summary')&&pdfText.includes('125.25')&&pdfText.includes('700.00'));
  assert(!pdfText.includes('SYNTHETIC AUDIT DATE'));
  assert.equal(await page.evaluate(()=>JSON.stringify(Object.fromEntries(Object.entries(localStorage)))),storage,'printing does not save or reset cash/audit facts');
  await amount(2,'74.76');await page.keyboard.press('Control+p');
  assert((await page.locator('#pvPaper').textContent()).includes('Shortage: 0.01 €'),'Ctrl+P routes to current cashier summary');
  await page.locator('#pvCancel').click();
  await amount(2,'74.74');await page.locator('#cashierPrint').click();assert((await page.locator('#pvPaper').textContent()).includes('Surplus: 0.01 €'));await page.locator('#pvCancel').click();
  await amount(2,'');assert(await page.locator('#cashierPrint').isDisabled());
  await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  assert((await page.locator('#printSheet').textContent()).includes('Complete both payment amounts'),'native print cannot retain a previous valid summary after invalid input');
  assert(!(await page.locator('#printSheet').textContent()).includes('700.00'));
  await page.locator('#cashierBack').click();
  await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  assert((await page.locator('#printSheet').textContent()).includes('SYNTHETIC AUDIT DATE'),'leaving cashier returns to department print routing');
  await page.evaluate(()=>window.__t.setModel(null));await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));assert.equal(await page.locator('#printSheet').textContent(),'','no stale summary with no audit loaded');
  await page.locator('#mLang').evaluate(n=>n.click());await page.locator('#cashierBtn').click();
  await page.locator('#cashierCounts input').evaluateAll(nodes=>nodes.forEach(n=>{n.value='1';n.dispatchEvent(new Event('input',{bubbles:true}));}));
  await amount(1,'388.88');await amount(2,'0');await page.locator('#cashierPrint').click();
  assert.equal(await page.locator('#pvPaper tbody').first().locator('tr').count(),15);
  await page.screenshot({path:path.join(__dirname,'cashier-print-greek.png'),fullPage:true});
  const greekPdf=path.join(tmp,'greek-summary.pdf');await page.pdf({path:greekPdf,format:'A4',preferCSSPageSize:true});
  const greekText=cp.execFileSync('pdftotext',[greekPdf,'-'],{encoding:'utf8'}),greekInfo=cp.execFileSync('pdfinfo',[greekPdf],{encoding:'utf8'});
  assert(/Pages:\s+1\b/.test(greekInfo),'all 15 denominations fit one Greek PDF page');
  for(const text of ['Σύνοψη Εσόδων','Προκαταβολή','Πληρωμή με μετρητά','888.88'])assert(greekText.includes(text),text);
  await page.locator('#pvCancel').click();await page.locator('#cashierReset').click();
  await amount(1,'0');await amount(2,'0');await page.locator('#cashierBase').fill('0');
  await page.locator('#cashierPrint').click();assert((await page.locator('#pvPaper').textContent()).includes('Σύνοψη Εσόδων'));assert((await page.locator('#pvPaper').textContent()).includes('Προκαταβολή'));assert((await page.locator('#pvPaper').textContent()).includes('Δεν καταμετρήθηκαν μετρητά'));
  await page.locator('#pvGo').click();await page.locator('#cashierBack').click();await page.waitForTimeout(150);
  assert.equal(await page.evaluate(()=>window.__prints),1,'navigation cancels the delayed print');
  assert.deepEqual(errors,[]);
  console.log('PASS cashier print: non-zero breakdown, exact payment/base totals, surplus/shortage, Greek/English, Ctrl+P, frozen preview, one-page A4 PDF, invalid-input guard, navigation cancellation and audit/storage isolation.');
 }finally{if(browser)await browser.close();server.close();fs.rmSync(tmp,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1});
